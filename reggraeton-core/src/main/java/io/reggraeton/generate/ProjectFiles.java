package io.reggraeton.generate;

import io.reggraeton.model.ProjectLayout;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/** Templates of the non-Java files of a generated project: pom.xml, Jenkinsfile, README, .gitignore. */
final class ProjectFiles {

    static final String PLAYWRIGHT_VERSION = "1.63.0";
    static final String JUNIT_VERSION = "6.1.3";
    static final String CUCUMBER_VERSION = "8.0.4";
    static final String TAG_EXPRESSIONS_VERSION = "11.0.1";
    static final String JACKSON_VERSION = "2.22.4";

    private ProjectFiles() {
    }

    static String pom(ConvertOptions options, ProjectLayout legacy, boolean lambdaGlue) {
        boolean bdd = options.mode() == ConvertOptions.Mode.BDD;
        List<String> deps = new ArrayList<>();
        deps.add(dep("com.microsoft.playwright", "playwright", "${playwright.version}"));
        deps.add(dep("org.junit.jupiter", "junit-jupiter", "${junit.version}"));
        if (bdd) {
            deps.add(dep("org.junit.platform", "junit-platform-suite", "${junit.version}"));
            deps.add(dep("io.cucumber", "cucumber-java", "${cucumber.version}"));
            if (lambdaGlue) {
                deps.add(dep("io.cucumber", "cucumber-java8", "${cucumber.version}"));
            }
            deps.add(dep("io.cucumber", "cucumber-junit-platform-engine", "${cucumber.version}"));
            deps.add(dep("io.cucumber", "cucumber-picocontainer", "${cucumber.version}"));
            // Cucumber 8 writes its reports (html plugin) with Jackson
            deps.add(dep("com.fasterxml.jackson.core", "jackson-databind", JACKSON_VERSION));
            deps.add(dep("com.fasterxml.jackson.datatype", "jackson-datatype-jdk8", JACKSON_VERSION));
        } else {
            deps.add(dep("io.cucumber", "tag-expressions", TAG_EXPRESSIONS_VERSION));
        }
        // assertion libraries the legacy code uses, at the versions it used
        for (Map.Entry<String, String> lib : legacy.libraries().entrySet()) {
            String key = lib.getKey();
            String version = lib.getValue();
            if (version == null || version.equals("?") || version.contains("${")) {
                version = switch (key) {
                    case "org.assertj:assertj-core" -> "3.27.7";
                    case "org.hamcrest:hamcrest" -> "3.0";
                    case "junit:junit" -> "4.13.2";
                    default -> null;
                };
            }
            if (version != null && (key.equals("org.assertj:assertj-core") || key.equals("org.hamcrest:hamcrest")
                    || key.equals("org.hamcrest:hamcrest-all") || key.equals("org.hamcrest:java-hamcrest")
                    || key.equals("junit:junit") || key.equals("com.google.truth:truth"))) {
                String[] ga = key.split(":");
                deps.add(dep(ga[0], ga[1], version));
            }
        }

        String includes = bdd ? """
                          <includes>
                            <include>**/RunRegressionTest.java</include>
                          </includes>
                """ : "";
        return """
                <?xml version="1.0" encoding="UTF-8"?>
                <!-- Generated by reggraeton (%s mode). Regenerate with `reggraeton convert` or edit freely. -->
                <project xmlns="http://maven.apache.org/POM/4.0.0"
                         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
                         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
                  <modelVersion>4.0.0</modelVersion>

                  <groupId>%s</groupId>
                  <artifactId>%s</artifactId>
                  <version>1.0.0-SNAPSHOT</version>
                  <name>Playwright regression tests</name>

                  <properties>
                    <maven.compiler.release>17</maven.compiler.release>
                    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
                    <playwright.version>%s</playwright.version>
                    <junit.version>%s</junit.version>
                    <cucumber.version>%s</cucumber.version>
                  </properties>

                  <dependencies>
                %s
                  </dependencies>

                  <build>
                    <plugins>
                      <plugin>
                        <groupId>org.apache.maven.plugins</groupId>
                        <artifactId>maven-compiler-plugin</artifactId>
                        <version>3.14.0</version>
                      </plugin>
                      <plugin>
                        <groupId>org.apache.maven.plugins</groupId>
                        <artifactId>maven-surefire-plugin</artifactId>
                        <version>3.5.6</version>
                        <configuration>
                %s          <environmentVariables>
                            <!-- never download browsers: the installed Edge (or -Dbrowser.channel/-Dbrowser.executable) is used -->
                            <PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD>1</PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD>
                          </environmentVariables>
                          <trimStackTrace>false</trimStackTrace>
                        </configuration>
                      </plugin>
                    </plugins>
                  </build>
                </project>
                """.formatted(bdd ? "bdd" : "native", options.groupId(), options.artifactId(), PLAYWRIGHT_VERSION,
                JUNIT_VERSION, CUCUMBER_VERSION, String.join("\n", deps), includes);
    }

    private static String dep(String group, String artifact, String version) {
        return """
                    <dependency>
                      <groupId>%s</groupId>
                      <artifactId>%s</artifactId>
                      <version>%s</version>
                      <scope>test</scope>
                    </dependency>""".formatted(group, artifact, version);
    }

    static String jenkinsfile() {
        return """
                // Generated by reggraeton. Runs the Playwright regression tests against a running web app.
                // Requirements on the agent: JDK 17+, Maven 3.9+ on the PATH (or add a `tools { maven '...' }` block),
                // and an installed Chromium-based browser (Microsoft Edge by default). Browsers are never downloaded.
                pipeline {
                    agent any

                    parameters {
                        string(name: 'BASE_URL', defaultValue: 'http://localhost:8080', description: 'URL of the running web application')
                        string(name: 'TAGS', defaultValue: '', description: 'Optional Cucumber tag expression, e.g. @smoke and not @wip')
                        choice(name: 'BROWSER_CHANNEL', choices: ['msedge', 'chrome', 'chromium'], description: 'Installed browser to use')
                        booleanParam(name: 'HEADLESS', defaultValue: true, description: 'Untick to watch the browser (needs a desktop session on the agent)')
                    }

                    options {
                        buildDiscarder(logRotator(numToKeepStr: '30'))
                    }

                    environment {
                        PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD = '1'
                        BASE_URL = "${params.BASE_URL}"
                        HEADLESS = "${params.HEADLESS}"
                        BROWSER_CHANNEL = "${params.BROWSER_CHANNEL}"
                        CUCUMBER_FILTER_TAGS = "${params.TAGS}"
                    }

                    stages {
                        stage('Regression tests') {
                            steps {
                                script {
                                    def tags = params.TAGS?.trim() ? " \\"-Dcucumber.filter.tags=${params.TAGS.trim()}\\"" : ''
                                    def command = "mvn -B test${tags}"
                                    if (isUnix()) {
                                        sh command
                                    } else {
                                        bat command
                                    }
                                }
                            }
                        }
                    }

                    post {
                        always {
                            junit testResults: 'target/surefire-reports/*.xml', allowEmptyResults: true
                            archiveArtifacts artifacts: 'target/playwright-artifacts/**, target/cucumber-report.html', allowEmptyArchive: true
                        }
                    }
                }
                """;
    }

    static String gitignore() {
        return "target/\n.idea/\n*.iml\n.vscode/\n";
    }

    static String readme(ConvertOptions options, int tests, int todos, int blocked) {
        boolean bdd = options.mode() == ConvertOptions.Mode.BDD;
        String filter = "-Dcucumber.filter.tags=\"@smoke and not @wip\"";
        String single = bdd ? "mvn test -Dcucumber.features=src/test/resources/features/<file>.feature:<line>"
                : "mvn test -Dtest=<TestClass>#<method>";
        return """
                # Playwright regression tests

                Generated by **reggraeton** (%s mode) from an existing Cucumber + Selenium suite:
                %d tests, one per original scenario / Examples row. See `traceability.csv` for the mapping
                from every original scenario to its test and `conversion-report.md` for what still needs a
                human (%d `TODO(reggraeton)` places, %d tests with undefined/ambiguous steps).

                ## Requirements

                - JDK 17+ and Maven 3.9+
                - an installed Chromium-based browser: **Microsoft Edge** by default. Browsers are **never
                  downloaded** (`PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD=1` is always set).
                - the web application running somewhere reachable (default `http://localhost:8080`)

                ## Running locally

                ```
                mvn test                                   # headless, Edge, http://localhost:8080
                mvn test -DbaseUrl=http://localhost:3000   # another application URL
                mvn test -Dheadless=false                  # windowed: watch the browser
                mvn test -Dheadless=false -DslowMo=250     # windowed and slowed down
                mvn test %s
                %s
                ```

                Browser selection (all must already be installed):

                | | |
                |---|---|
                | `-Dbrowser.channel=msedge` | Microsoft Edge (default) |
                | `-Dbrowser.channel=chrome` | Google Chrome |
                | `-Dbrowser.channel=chromium` | Chromium found in `PLAYWRIGHT_BROWSERS_PATH` |
                | `-Dbrowser.executable=/path/to/browser` | any Chromium-based binary |

                Every setting can also come from an environment variable: `BASE_URL`, `HEADLESS`,
                `BROWSER_CHANNEL`, `BROWSER_EXECUTABLE`, `SLOW_MO`, `PW_TIMEOUT` (ms, default 15000),
                `PW_NAVIGATION_TIMEOUT`, `VIEWPORT` (e.g. `1920x1080`), `PW_TRACE` (`on-failure`, `on`, `off`),
                `ARTIFACTS_DIR`, `CUCUMBER_FILTER_TAGS`.

                ## Results

                - JUnit XML: `target/surefire-reports/`%s
                - on failure: a screenshot and a Playwright trace in `target/playwright-artifacts/`.
                  Open a trace by dropping the zip on https://trace.playwright.dev (it is processed locally in the browser).

                ## Jenkins

                The `Jenkinsfile` runs `mvn test` with parameters `BASE_URL`, `TAGS`, `BROWSER_CHANNEL` and
                `HEADLESS`, on Linux or Windows agents, publishes the JUnit results and archives the
                screenshots/traces. The agent needs JDK, Maven and the browser installed.

                ## Finishing the conversion

                Search for `TODO(reggraeton)`: each one marks code without an automatic Playwright
                equivalent. Until it is rewritten it throws `PendingConversionException`, so the affected
                tests fail instead of passing silently. `conversion-report.md` lists them all.

                ## Layout

                | Path | Content |
                |---|---|
                %s| `src/test/java/<your packages>` | step definitions, page objects and helpers, translated to Playwright |
                | `src/test/java/%s` | runtime support (browser session, configuration, waits) |
                """.formatted(bdd ? "bdd" : "native", tests, todos, blocked, filter, single,
                bdd ? ", Cucumber HTML report: `target/cucumber-report.html`" : "",
                bdd ? "| `src/test/resources/features` | the original feature files, unchanged |\n| `src/test/java/" + options.basePackage().replace('.', '/')
                        + "/RunRegressionTest.java` | JUnit Platform suite that runs the features |\n"
                        : "| `src/test/java/" + options.basePackage().replace('.', '/') + "/features` | one JUnit class per feature file |\n",
                options.supportPackage().replace('.', '/'));
    }
}
