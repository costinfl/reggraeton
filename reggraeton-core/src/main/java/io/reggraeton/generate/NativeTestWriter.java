package io.reggraeton.generate;

import io.reggraeton.model.FeatureFile;
import io.reggraeton.model.Hook;
import io.reggraeton.model.Inventory;
import io.reggraeton.model.ParameterTypeDefinition;
import io.reggraeton.model.ScenarioDefinition;
import io.reggraeton.model.StepMatch;
import io.reggraeton.model.TestCase;
import io.reggraeton.model.TestStep;
import io.reggraeton.naming.TestNaming;
import io.reggraeton.scan.Assessor;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Collectors;

/**
 * native mode: writes one JUnit 5 class per feature file. A scenario is a {@code @Test}; a
 * Scenario Outline is a {@code @ParameterizedTest} with one invocation per Examples row. Every
 * step is a direct call to the converted step method, with its arguments converted here.
 */
final class NativeTestWriter {

    /** One generated test class. */
    record TestClass(String relativePath, String qualifiedName, String source, int tests, List<String> testCaseIds) {
    }

    private final Inventory inventory;
    private final TestNaming naming;
    private final String supportPackage;
    private final NativeGlueRewriter.Result glue;
    private final ArgumentRenderer arguments;
    private final Map<String, Hook> hooksById = new LinkedHashMap<>();

    NativeTestWriter(Inventory inventory, TestNaming naming, String supportPackage, NativeGlueRewriter.Result glue,
                     Map<String, ParameterTypeDefinition> parameterTypes) {
        this.inventory = inventory;
        this.naming = naming;
        this.supportPackage = supportPackage;
        this.glue = glue;
        this.arguments = new ArgumentRenderer(parameterTypes, glue.enums());
        inventory.hooks().forEach(h -> hooksById.put(h.id(), h));
    }

    List<TestClass> write() {
        List<TestClass> classes = new ArrayList<>();
        Map<String, List<TestCase>> byFeature = new LinkedHashMap<>();
        inventory.testCases().forEach(tc -> byFeature.computeIfAbsent(tc.feature(), k -> new ArrayList<>()).add(tc));
        for (FeatureFile feature : inventory.features()) {
            List<TestCase> cases = byFeature.get(feature.path());
            if (feature.parseError() != null || cases == null) {
                continue;
            }
            classes.add(writeClass(feature, cases));
        }
        return classes;
    }

    private TestClass writeClass(FeatureFile feature, List<TestCase> cases) {
        String qualified = naming.classFor(feature.path());
        String pkg = qualified.substring(0, qualified.lastIndexOf('.'));
        String simple = qualified.substring(qualified.lastIndexOf('.') + 1);
        Imports imports = new Imports(pkg);
        imports.add("org.junit.jupiter.api.DisplayName");
        imports.add(supportPackage + ".RegressionTest");

        StringBuilder body = new StringBuilder();
        int tests = 0;
        List<String> ids = new ArrayList<>();
        Map<Integer, List<TestCase>> byScenario = new LinkedHashMap<>();
        cases.forEach(tc -> byScenario.computeIfAbsent(tc.scenarioLine(), k -> new ArrayList<>()).add(tc));
        for (ScenarioDefinition scenario : feature.scenarios()) {
            List<TestCase> scenarioCases = byScenario.get(scenario.line());
            if (scenarioCases == null) {
                continue;
            }
            String method = naming.methodFor(feature.path(), scenario.line());
            body.append('\n');
            if (scenario.outline()) {
                writeOutline(body, imports, feature, scenario, method, scenarioCases);
            } else {
                writeScenario(body, imports, feature, scenario, method, scenarioCases.get(0));
            }
            tests += scenarioCases.size();
            scenarioCases.forEach(tc -> ids.add(tc.id()));
        }

        StringBuilder src = new StringBuilder();
        src.append("package ").append(pkg).append(";\n\n");
        src.append(imports.render()).append('\n');
        src.append("/**\n * ").append(JavaLiterals.comment(feature.keyword() + ": " + feature.name())).append("\n *\n");
        src.append(" * <p>Generated by reggraeton from {@code ").append(JavaLiterals.comment(feature.path()))
                .append("}: one test per scenario and per Examples row.</p>\n */\n");
        src.append("@DisplayName(").append(JavaLiterals.string(feature.name())).append(")\n");
        src.append("class ").append(simple).append(" extends RegressionTest {\n");
        src.append(body);
        src.append("}\n");
        String relative = qualified.replace('.', '/') + ".java";
        return new TestClass(relative, qualified, src.toString(), tests, ids);
    }

    private void writeScenario(StringBuilder out, Imports imports, FeatureFile feature, ScenarioDefinition scenario,
                               String method, TestCase testCase) {
        imports.add("org.junit.jupiter.api.Test");
        out.append("    /** ").append(JavaLiterals.comment(scenario.keyword() + ": " + scenario.name()))
                .append(" ({@code ").append(JavaLiterals.comment(testCase.id())).append("}) */\n");
        out.append("    @Test\n");
        out.append("    @DisplayName(").append(JavaLiterals.string(scenario.name())).append(")\n");
        tags(out, imports, testCase.tags());
        out.append("    void ").append(method).append("() throws Throwable {\n");
        writeBody(out, imports, testCase, "        ");
        out.append("    }\n");
    }

    private void writeOutline(StringBuilder out, Imports imports, FeatureFile feature, ScenarioDefinition scenario,
                              String method, List<TestCase> rows) {
        imports.add("org.junit.jupiter.params.ParameterizedTest");
        imports.add("org.junit.jupiter.params.provider.MethodSource");
        imports.add("org.junit.jupiter.params.provider.Arguments");
        imports.add("org.junit.jupiter.api.Named");
        imports.add("java.util.stream.Stream");
        Set<String> allTags = new LinkedHashSet<>();
        rows.forEach(r -> allTags.addAll(r.tags()));

        out.append("    /** ").append(JavaLiterals.comment(scenario.keyword() + ": " + scenario.name()))
                .append(" ({@code ").append(JavaLiterals.comment(feature.path() + ":" + scenario.line()))
                .append("}), one invocation per Examples row. */\n");
        out.append("    @ParameterizedTest(name = \"[{index}] {0}\")\n");
        out.append("    @MethodSource(").append(JavaLiterals.string(method + "Examples")).append(")\n");
        out.append("    @DisplayName(").append(JavaLiterals.string(scenario.name())).append(")\n");
        tags(out, imports, new ArrayList<>(allTags));
        out.append("    void ").append(method).append("(int row) throws Throwable {\n");
        out.append("        switch (row) {\n");
        for (TestCase row : rows) {
            out.append("            case ").append(row.exampleIndex()).append(" -> {\n");
            writeBody(out, imports, row, "                ");
            out.append("            }\n");
        }
        out.append("            default -> throw new IllegalArgumentException(\"no Examples row \" + row);\n");
        out.append("        }\n    }\n\n");

        out.append("    static Stream<Arguments> ").append(method).append("Examples() {\n");
        out.append("        return Stream.of(\n");
        List<String> entries = new ArrayList<>();
        for (TestCase row : rows) {
            entries.add("                Arguments.of(Named.of(" + JavaLiterals.string(rowLabel(scenario, row)) + ", "
                    + row.exampleIndex() + "))");
        }
        out.append(String.join(",\n", entries)).append(");\n    }\n");
    }

    private static String rowLabel(ScenarioDefinition scenario, TestCase row) {
        for (ScenarioDefinition.ExamplesBlock block : scenario.examples()) {
            for (ScenarioDefinition.ExampleRow r : block.rows()) {
                if (r.line() == row.exampleLine()) {
                    List<String> pairs = new ArrayList<>();
                    for (int i = 0; i < block.header().size() && i < r.values().size(); i++) {
                        pairs.add(block.header().get(i) + "=" + r.values().get(i));
                    }
                    return (block.name() == null ? "" : block.name() + ": ") + String.join(", ", pairs);
                }
            }
        }
        return "line " + row.exampleLine();
    }

    private void writeBody(StringBuilder out, Imports imports, TestCase testCase, String indent) {
        out.append(indent).append("scenario(").append(JavaLiterals.string(testCase.id())).append(", ")
                .append(JavaLiterals.string(testCase.name()));
        for (String tag : testCase.tags()) {
            out.append(", ").append(JavaLiterals.string(tag));
        }
        out.append(");\n");

        List<Hook> applicable = inventory.hooks().stream()
                .filter(h -> Assessor.appliesTo(h, testCase.tags()))
                .toList();
        applicable.stream().filter(h -> h.phase().equals("Before"))
                .sorted(Comparator.comparingInt(Hook::order))
                .forEach(h -> out.append(indent).append("before(() -> ").append(hookCall(h, imports)).append(");\n"));
        applicable.stream().filter(h -> h.phase().equals("After"))
                .sorted(Comparator.comparingInt(Hook::order).reversed())
                .forEach(h -> out.append(indent).append("after(() -> ").append(hookCall(h, imports)).append(");\n"));
        List<Hook> beforeStep = applicable.stream().filter(h -> h.phase().equals("BeforeStep"))
                .sorted(Comparator.comparingInt(Hook::order)).toList();
        List<Hook> afterStep = applicable.stream().filter(h -> h.phase().equals("AfterStep"))
                .sorted(Comparator.comparingInt(Hook::order).reversed()).toList();

        boolean background = false;
        for (TestStep step : testCase.steps()) {
            if (step.fromBackground() && !background) {
                out.append(indent).append("// Background\n");
                background = true;
            } else if (!step.fromBackground() && background) {
                out.append(indent).append("// Scenario\n");
                background = false;
            }
            String text = step.keyword() + " " + step.text();
            String call = stepCall(testCase, step, imports);
            if (!beforeStep.isEmpty() || !afterStep.isEmpty()) {
                StringBuilder wrapped = new StringBuilder("{ ");
                beforeStep.forEach(h -> wrapped.append(hookCall(h, imports)).append("; "));
                wrapped.append("try { ").append(call).append("; } finally { ");
                afterStep.forEach(h -> wrapped.append(hookCall(h, imports)).append("; "));
                call = wrapped.append("} }").toString();
            }
            out.append(indent).append("step(").append(JavaLiterals.string(text)).append(", () -> ").append(call).append(");\n");
        }
    }

    private String stepCall(TestCase testCase, TestStep step, Imports imports) {
        StepMatch match = step.match();
        String where = testCase.feature().substring(testCase.feature().lastIndexOf('/') + 1) + ":" + step.line();
        if (match == null || StepMatch.UNDEFINED.equals(match.status())) {
            return "undefined(" + JavaLiterals.string("Undefined step (" + where + "): no step definition matches \"" + step.text() + "\"") + ")";
        }
        if (StepMatch.AMBIGUOUS.equals(match.status())) {
            return "undefined(" + JavaLiterals.string("Ambiguous step (" + where + "): \"" + step.text() + "\" matches "
                    + String.join(", ", match.stepDefinitionIds())) + ")";
        }
        NativeGlueRewriter.Target target = glue.steps().get(match.stepDefinitionIds().get(0));
        if (target == null) {
            imports.add(supportPackage + ".PendingConversion");
            return "PendingConversion.fail(" + JavaLiterals.string(where + ": step definition "
                    + match.stepDefinitionIds().get(0) + " could not be converted") + ")";
        }
        ArgumentRenderer.Rendered rendered = arguments.render(match.arguments(), step.argument(), target.parameterTypes(),
                (cls, method, arg) -> "glue(" + imports.type(cls) + ".class)." + method + "(" + arg + ")");
        if (rendered.failed()) {
            imports.add(supportPackage + ".PendingConversion");
            return "PendingConversion.fail(" + JavaLiterals.string(where + ": " + rendered.problem()) + ")";
        }
        if (step.argument() != null && step.argument().isDataTable()) {
            imports.add(supportPackage + ".DataTable");
        }
        return "glue(" + imports.type(target.className()) + ".class)." + target.methodName() + "("
                + String.join(", ", rendered.expressions()) + ")";
    }

    private String hookCall(Hook hook, Imports imports) {
        NativeGlueRewriter.Target target = glue.hooks().get(hook.id());
        if (target == null) {
            imports.add(supportPackage + ".PendingConversion");
            return "PendingConversion.fail(" + JavaLiterals.string("hook " + hook.id() + " could not be converted") + ")";
        }
        List<String> args = new ArrayList<>();
        for (String type : target.parameterTypes()) {
            if (ArgumentRenderer.normalise(type).endsWith("Scenario")) {
                args.add("currentScenario()");
            } else {
                imports.add(supportPackage + ".PendingConversion");
                return "PendingConversion.fail(" + JavaLiterals.string("hook " + hook.id() + " takes a " + type
                        + " parameter, which is not supported in native mode") + ")";
            }
        }
        return "glue(" + imports.type(target.className()) + ".class)." + target.methodName() + "(" + String.join(", ", args) + ")";
    }

    private static void tags(StringBuilder out, Imports imports, List<String> tags) {
        Set<String> valid = new TreeSet<>();
        for (String tag : tags) {
            String t = tag.startsWith("@") ? tag.substring(1) : tag;
            if (!t.isBlank() && t.chars().noneMatch(c -> Character.isWhitespace(c) || Character.isISOControl(c) || ",()&|!".indexOf(c) >= 0)) {
                valid.add(t);
            }
        }
        if (!valid.isEmpty()) {
            imports.add("org.junit.jupiter.api.Tag");
            out.append("    ").append(valid.stream().map(t -> "@Tag(" + JavaLiterals.string(t) + ")")
                    .collect(Collectors.joining(" "))).append('\n');
        }
    }

    /** Import bookkeeping; falls back to qualified names on simple-name clashes. */
    static final class Imports {
        private final String ownPackage;
        private final Map<String, String> bySimpleName = new LinkedHashMap<>();

        Imports(String ownPackage) {
            this.ownPackage = ownPackage;
        }

        void add(String qualified) {
            type(qualified);
        }

        /** Simple name if it can be imported, else the qualified name. */
        String type(String qualified) {
            String simple = qualified.substring(qualified.lastIndexOf('.') + 1);
            String existing = bySimpleName.putIfAbsent(simple, qualified);
            if (existing == null || existing.equals(qualified)) {
                return simple;
            }
            return qualified;
        }

        String render() {
            return bySimpleName.values().stream()
                    .filter(q -> !q.substring(0, q.lastIndexOf('.')).equals(ownPackage))
                    .sorted()
                    .map(q -> "import " + q + ";\n")
                    .collect(Collectors.joining());
        }
    }
}
